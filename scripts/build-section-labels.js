/**
 * Writes src/components/panel/sectionLabels.js: the label of every control in
 * every panel section, so the filter finds a slider by its own name.
 *
 * `sectionTerms.js` is written by hand and names what a section is about. It
 * cannot keep up with what a section *holds*: "azimuth" found Hillshade and
 * missed five marks with an Azimuth slider. Scraping the rendered panel is no
 * answer either, because a mark's controls mount only while it is drawing,
 * which is exactly when nobody is searching for it. So the labels are read
 * from the source, between each `<Section title="…">` and its `</Section>`.
 *
 * Only literal `label="…"` props count. The shared Line style block that every
 * mark renders (ModeStyleOverride) is not inside any one section's source, so
 * "weight" does not match all sixty marks.
 *
 * Usage:
 *   node scripts/build-section-labels.js      # rewrite the module
 *
 * `tests/unit/sectionLabels.test.js` fails when the module is stale.
 */
import { readFileSync, writeFileSync } from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const SOURCES = [
  'src/components/Sidebar.jsx',
  'src/components/panel/ModeSections.jsx',
  'src/components/panel/ErosionSection.jsx',
  'src/components/panel/TextSection.jsx',
]
export const OUT = 'src/components/panel/sectionLabels.js'

/** `{ title: 'label label …' }` for every section in one source text. */
export function labelsIn(src) {
  const out = {}
  // Every opening and closing tag, in order. Sections do not nest, but a
  // stack costs nothing and makes a nested one fail loudly rather than quietly.
  const tags = /<Section\s+title="([^"]+)"|<\/Section>/g
  const open = []
  let m
  while ((m = tags.exec(src))) {
    if (m[1]) { open.push({ title: m[1], from: tags.lastIndex }); continue }
    const sec = open.pop()
    if (!sec) throw new Error(`</Section> without an opening tag at ${m.index}`)
    if (open.length) throw new Error(`Section "${sec.title}" is nested in "${open.at(-1).title}"`)
    const body = src.slice(sec.from, m.index)
    const words = new Set(out[sec.title]?.split(' ') ?? [])
    for (const [, label] of body.matchAll(/\blabel="([^"]+)"/g)) {
      for (const w of label.toLowerCase().split(/[^a-z0-9α-ω°%-]+/)) if (w.length > 1) words.add(w)
    }
    if (words.size) out[sec.title] = [...words].join(' ')
  }
  if (open.length) throw new Error(`Section "${open[0].title}" is never closed`)
  return out
}

/** The module text for every source together, sorted so the file diffs cleanly. */
export function buildModule() {
  const all = {}
  for (const f of SOURCES) Object.assign(all, labelsIn(readFileSync(resolve(ROOT, f), 'utf8')))
  const rows = Object.keys(all).sort().map((t) => `  ${JSON.stringify(t)}: ${JSON.stringify(all[t])},`)
  return `/**
 * The labels of the controls inside each panel section, for the filter.
 *
 * Generated by scripts/build-section-labels.js from the panel source. Do not
 * edit; run \`npm run section-labels\` after a label changes. A leaf module, for
 * the reason sectionTerms.js gives.
 */
export const SECTION_LABELS = {
${rows.join('\n')}
}
`
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(resolve(ROOT, OUT), buildModule())
  console.log(`Wrote ${OUT}`)
}
